'use client';

import { Expand } from 'lucide-react';
import Image from 'next/image';
import { useEffect, useState } from 'react';

import { ScreenPinOverlay } from '@/components/handoff/ScreenPinOverlay';
import { useScreenPinRequestFor } from '@/components/handoff/ScreenPinProvider';
import { Button } from '@/components/ui/Button';
import { Modal } from '@/components/ui/Modal';
import { cn } from '@/lib/cn';
import type { ScreenPin } from '@/lib/screenPins';
import type { ScreenAnalysisStatus } from '@/lib/types';

type ScreenThumbnailProps = {
  name: string;
  imageUrl: string;
  analysisStatus: ScreenAnalysisStatus;
  /**
   * Both optional — the preview/share pages reuse this component via
   * ScreensSection.tsx with no ScreenPinProvider mounted and no pin data,
   * and continue to render exactly as before with neither prop passed.
   */
  screenId?: string;
  pins?: ScreenPin[];
  className?: string;
};

const STATUS_LABEL: Record<ScreenAnalysisStatus, string> = {
  Pending: 'Pending analysis',
  Analyzing: 'Analyzing…',
  Analyzed: 'Analyzed',
  Failed: 'Analysis failed',
};

/**
 * `imageUrl` is a short-lived signed GET URL (lib/storage.ts) generated by
 * the parent server component — design assets are never served from a
 * public bucket. See security.md's File Uploads section. Clicking the
 * thumbnail opens a full-size view — the only way to see an uploaded screen
 * at full resolution anywhere in the app, in both the designer review page
 * and the public share view since both compose this component.
 */
export function ScreenThumbnail({ name, imageUrl, analysisStatus, screenId, pins = [], className }: ScreenThumbnailProps) {
  const [isExpanded, setIsExpanded] = useState(false);
  const pinRequest = useScreenPinRequestFor(screenId ?? '');

  useEffect(() => {
    if (pinRequest) {
      setIsExpanded(true);
    }
    // Re-open on every new request for this screen, keyed off requestId —
    // not screenId/highlightedKey, which can be unchanged between clicks.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [pinRequest?.requestId]);

  return (
    <div className={cn('flex flex-col gap-1.5', className)}>
      <button
        type="button"
        onClick={() => setIsExpanded(true)}
        aria-label={`View ${name} full size`}
        className="group relative aspect-video overflow-hidden rounded-[--radius-md] border border-[--color-border] bg-[--color-surface] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[--color-primary]"
      >
        <Image src={imageUrl} alt={`${name} screen`} fill sizes="240px" className="object-cover object-top" />
        <span className="absolute inset-0 flex items-center justify-center bg-black/0 opacity-0 transition group-hover:bg-black/30 group-hover:opacity-100">
          <Expand aria-hidden="true" size={20} className="text-white" />
        </span>
        {/* No positioning math here — the grid tile crops with object-cover,
            so exact pin placement isn't achievable at this size; a plain
            count is still a useful teaser for the pins in the expanded view. */}
        {pins.length > 0 && (
          <span className="absolute right-1.5 top-1.5 rounded-[--radius-full] bg-[--color-primary] px-1.5 py-0.5 text-[length:var(--font-desktop-caption-medium-size)] font-medium text-white">
            {pins.length} finding{pins.length === 1 ? '' : 's'}
          </span>
        )}
      </button>
      <span className="text-[--color-text-body]">{name}</span>
      <span className="text-[--color-text-secondary]">{STATUS_LABEL[analysisStatus]}</span>

      <Modal open={isExpanded} onClose={() => setIsExpanded(false)} title={name} className="max-w-4xl">
        <div className="relative aspect-video w-full overflow-hidden rounded-[--radius-md] bg-[--color-surface]">
          {screenId ? (
            <ScreenPinOverlay screenId={screenId} name={name} imageUrl={imageUrl} pins={pins} />
          ) : (
            <Image src={imageUrl} alt={`${name} screen, full size`} fill sizes="90vw" className="object-contain" />
          )}
        </div>
        <Button type="button" variant="secondary" onClick={() => setIsExpanded(false)} className="self-end">
          Close
        </Button>
      </Modal>
    </div>
  );
}
